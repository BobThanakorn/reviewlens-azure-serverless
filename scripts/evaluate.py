"""Measure classifier accuracy from the processed blobs and write docs/evaluation.md.

Ground truth comes from the star rating (1-2 negative, 3 neutral, 4-5 positive). Every number in
the report is computed from the data; nothing is typed by hand. Uses Entra auth (az login) and
the data account URL from Terraform output or --account-url.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from collections import Counter
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from api.aggregate import PREDICTED_LABELS, accuracy_stats  # noqa: E402
from common.models import SENTIMENTS, stars_to_sentiment  # noqa: E402

REPORT = ROOT / "docs" / "evaluation.md"
ANALYSIS = ROOT / "docs" / "evaluation-analysis.md"  # hand-written after reading real results
EXAMPLE_COUNT = 5
TEXT_LIMIT = 200


def load_processed(store: Any) -> list[dict[str, Any]]:
    """Read every processed chunk, de-duplicating by review_id (latest processing wins)."""
    latest: dict[int, dict[str, Any]] = {}
    for name in store.list_names("processed", "dt="):
        for line in store.read_text("processed", name).splitlines():
            if line.strip():
                review = json.loads(line)
                current = latest.get(review["review_id"])
                if current is None or review["processed_at"] >= current["processed_at"]:
                    latest[review["review_id"]] = review
    return sorted(latest.values(), key=lambda r: r["review_id"])


def pick_examples(
    reviews: list[dict[str, Any]], count: int = EXAMPLE_COUNT
) -> list[dict[str, Any]]:
    """Misclassified reviews, one per (truth, predicted) cell first so the examples are varied."""
    wrong = [r for r in reviews if r["sentiment"] != stars_to_sentiment(int(r["stars"]))]
    seen: set[tuple[str, str]] = set()
    picked: list[dict[str, Any]] = []
    for r in wrong:  # already ordered by review_id
        cell = (stars_to_sentiment(int(r["stars"])), r["sentiment"])
        if cell not in seen:
            seen.add(cell)
            picked.append(r)
    for r in wrong:
        if len(picked) >= count:
            break
        if r not in picked:
            picked.append(r)
    return picked[:count]


def truncate(text: str, limit: int = TEXT_LIMIT) -> str:
    flat = " ".join(text.split())
    return flat if len(flat) <= limit else flat[: limit - 1] + "…"


def observations(stats: dict[str, Any], reviews: list[dict[str, Any]]) -> list[str]:
    """Data-driven remarks about where the classifier disagrees with the star rating."""
    matrix = stats["confusion_matrix"]
    errors = [
        (truth, pred, n)
        for truth, row in matrix.items()
        for pred, n in row.items()
        if pred != truth and n
    ]
    errors.sort(key=lambda e: -e[2])
    notes = []
    total_errors = sum(n for _, _, n in errors)
    for truth, pred, n in errors[:3]:
        share = n / total_errors * 100
        notes.append(
            f"{n} reviews with a **{truth}** star rating were labelled **{pred}** "
            f"({share:.0f}% of all errors)."
        )
    support = {t: sum(matrix[t].values()) for t in SENTIMENTS}
    for truth in SENTIMENTS:
        if support[truth]:
            recall = matrix[truth][truth] / support[truth] * 100
            notes.append(f"Recall for **{truth}** (by stars): {recall:.0f}% of {support[truth]}.")
    status = Counter(r.get("status", "ok") for r in reviews)
    if status.get("invalid_output") or status.get("error"):
        notes.append(
            f"{status.get('invalid_output', 0)} invalid-output and {status.get('error', 0)} "
            "error rows are counted as wrong."
        )
    return notes


def render(
    reviews: list[dict[str, Any]], generated_at: datetime | None = None, analysis: str | None = None
) -> str:
    stats = accuracy_stats(reviews)
    generated_at = generated_at or datetime.now(UTC)
    providers = sorted({f"{r['provider']}/{r['model']}" for r in reviews})
    tokens_in = sum(int(r.get("input_tokens", 0)) for r in reviews)
    tokens_out = sum(int(r.get("output_tokens", 0)) for r in reviews)
    labels = list(PREDICTED_LABELS)

    lines = [
        "# Evaluation",
        "",
        f"Generated by `scripts/evaluate.py` on {generated_at:%Y-%m-%d %H:%M} UTC. "
        "Do not edit by hand; re-run the script.",
        "",
        "## Method",
        "",
        "Ground truth is derived from the customer's star rating: 1-2 = negative, 3 = neutral, "
        "4-5 = positive. A review labelled `unknown` (invalid or failed output) counts as wrong. "
        "Stars are a noisy proxy for sentiment, so accuracy here measures agreement with the "
        "rating, not absolute correctness.",
        "",
        "## Results",
        "",
        f"- Provider / model: {', '.join(providers) or 'n/a'}",
        f"- Sample size: **{stats['sample_size']}** reviews",
        f"- Correct: {stats['correct']}",
        f"- Accuracy: **{stats['accuracy'] * 100:.1f}%**",
        f"- Tokens used: {tokens_in} input, {tokens_out} output",
        "",
        "### Confusion matrix (rows = stars-based truth, columns = predicted)",
        "",
        "| truth \\ predicted | " + " | ".join(labels) + " | total |",
        "|---|" + "---|" * (len(labels) + 1),
    ]
    for truth in SENTIMENTS:
        row = stats["confusion_matrix"][truth]
        lines.append(
            f"| {truth} | " + " | ".join(str(row[p]) for p in labels) + f" | {sum(row.values())} |"
        )

    star_counts = Counter(int(r["stars"]) for r in reviews)
    lines += [
        "",
        "### Class balance in this sample",
        "",
        "| stars | " + " | ".join(str(s) for s in range(1, 6)) + " |",
        "|---|" + "---|" * 5,
        "| reviews | " + " | ".join(str(star_counts.get(s, 0)) for s in range(1, 6)) + " |",
        "",
        "## Observations (computed from the data)",
        "",
        *[f"- {note}" for note in observations(stats, reviews)],
        "",
        f"## Misclassified examples (text truncated to {TEXT_LIMIT} characters)",
        "",
    ]
    for i, r in enumerate(pick_examples(reviews), start=1):
        truth = stars_to_sentiment(int(r["stars"]))
        lines += [
            f"{i}. review {r['review_id']}: {r['stars']} stars (truth **{truth}**), "
            f"predicted **{r['sentiment']}** / {r['topic']}",
            f"   > {truncate(r['review_text'])}",
            f"   > summary: {r.get('summary') or '-'}",
            "",
        ]
    if not pick_examples(reviews):
        lines += ["No misclassified reviews in this sample.", ""]
    if analysis and analysis.strip():
        lines += ["## Analysis", "", analysis.strip(), ""]
    return "\n".join(lines).rstrip() + "\n"


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--account-url", help="data account blob URL (default: terraform output)")
    p.add_argument("--out", type=Path, default=REPORT)
    p.add_argument(
        "--analysis", type=Path, default=ANALYSIS, help="optional hand-written analysis to embed"
    )
    return p.parse_args(argv)


def main(argv: list[str] | None = None, store: Any = None) -> int:
    args = parse_args(argv)
    if store is None:
        from common.storage import BlobStore

        url = args.account_url
        if not url:
            out = subprocess.run(
                ["terraform", "output", "-raw", "data_blob_url"],
                cwd=ROOT / "terraform" / "envs" / "dev", capture_output=True, text=True, check=True,
            )  # fmt: skip  # noqa: S607
            url = out.stdout.strip()
        store = BlobStore.from_account_url(url)
    reviews = load_processed(store)
    if not reviews:
        print("no processed reviews found; nothing to evaluate", file=sys.stderr)
        return 1
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(render(reviews), encoding="utf-8", newline="\n")
    stats = accuracy_stats(reviews)
    print(f"wrote {args.out}: {stats['sample_size']} reviews, accuracy {stats['accuracy']:.1%}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
